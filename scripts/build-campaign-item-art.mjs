import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readFileSync, writeFileSync} from 'node:fs';

const root=new URL('../',import.meta.url);
const manifest=JSON.parse(readFileSync(new URL('assets/item-art/v1/manifest.json',root),'utf8'));
const icons={},names={},fallbacks={};
for(const item of manifest.items){
  assert.ok(!icons[item.id],`duplicate illustration: ${item.id}`);
  const bytes=readFileSync(new URL(item.src,root));
  assert.equal(createHash('sha256').update(bytes).digest('hex'),item.sha256,`illustration hash: ${item.id}`);
  icons[item.id]={src:item.src,width:item.width,height:item.height,sha256:item.sha256,source:'original-item-illustration'};
  names[item.name]=item.id;
  if(!fallbacks[item.kind])fallbacks[item.kind]=item.id;
}
assert.equal(manifest.items.length,193,'every built-in item must have an illustration');
const fallback='data:image/webp;base64,'+readFileSync(new URL('assets/item-art/v1/fallback.webp',root)).toString('base64');
const output=`// Generated by scripts/build-campaign-item-art.mjs from the original illustration manifest.
(function(root,factory){const api=factory();if(typeof module==='object'&&module.exports)module.exports=api;if(root)root.DndWorldItemArt=api;})(typeof globalThis==='object'?globalThis:this,function(){
'use strict';
const icons=Object.freeze(${JSON.stringify(icons)});
const names=${JSON.stringify(names)};
const fallbacks=Object.freeze(${JSON.stringify(fallbacks)});
const fallbackData=${JSON.stringify(fallback)};
const key=value=>String(value||'').normalize('NFKC').trim().toLocaleLowerCase('ru').replace(/ё/g,'е').replace(/\\s+/g,' ');
const byName=new Map(Object.entries(names).map(([name,id])=>[key(name),id]));
function forItem(value){
const item=value&&value.item||value||{},explicit=value&&value.icon&&value.icon.src?value.icon:item.icon;
if(explicit&&explicit.src)return explicit;
const exact=Object.hasOwn(icons,item.id)?icons[item.id]:icons[byName.get(key(item.n||item.name||value&&value.name))];
if(exact)return exact;
const kind=value&&value.kind||item.mechanics&&item.mechanics.profile&&item.mechanics.profile.kind||item.kind||item.type;
return icons[fallbacks[kind]]||icons.it_рюкзак;
}
return Object.freeze({icons,fallbacks,fallbackData,forItem});
});
`;
const target=new URL('scripts/campaign-item-art.js',root);
if(process.argv.includes('--check'))assert.equal(readFileSync(target,'utf8'),output,'campaign artwork module must match its manifest');
else writeFileSync(target,output);
console.log(`Validated ${manifest.items.length} illustrated item definitions.`);
